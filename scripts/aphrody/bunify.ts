#!/usr/bin/env bun
// aphrody-labs/next.js: switch the repository from pnpm + Node to Bun, idempotently.
// Run after every upstream sync (`bun scripts/aphrody/bunify.ts`, then `bun install`):
// - pnpm-workspace.yaml -> package.json workspaces, overrides, patchedDependencies,
//   packageExtensions, trustedDependencies, and bunfig.toml (minimumReleaseAge);
// - every package.json script: pnpm/npx/node/cross-env -> bun/bunx;
// - JS/TS tooling that spawns pnpm or node -> bun.
import { Glob } from "bun";
import { existsSync, rmSync } from "node:fs";
import { join } from "node:path";

const ROOT = join(import.meta.dir, "../..");
const check = process.argv.includes("--check");
let changed = 0;
const save = async (path: string, before: string, after: string) => {
  if (before === after) return;
  changed++;
  if (!check) await Bun.write(path, after);
  else console.log(`would change ${path.slice(ROOT.length + 1)}`);
};

// ---- 1. Workspace manifest -----------------------------------------------------------------
const wsFile = join(ROOT, "pnpm-workspace.yaml");
const rootPkgPath = join(ROOT, "package.json");
const rootText = await Bun.file(rootPkgPath).text();
const rootPkg = JSON.parse(rootText);
if (existsSync(wsFile)) {
  const ws = Bun.YAML.parse(await Bun.file(wsFile).text()) as Record<string, any>;
  rootPkg.workspaces = ws.packages;
  rootPkg.overrides = { ...(ws.overrides ?? {}) };
  rootPkg.patchedDependencies = ws.patchedDependencies ?? {};
  rootPkg.trustedDependencies = Object.entries(ws.allowBuilds ?? {})
    .filter(([, v]) => v === true)
    .map(([k]) => k)
    .sort();
  if (ws.packageExtensions) rootPkg.packageExtensions = ws.packageExtensions;
  const ageSeconds = Number(ws.minimumReleaseAge ?? 0) * 60;
  const bunfig = [
    "# Generated by scripts/aphrody/bunify.ts from upstream pnpm-workspace.yaml.",
    "[install]",
    "exact = true",
    "linkWorkspacePackages = true",
    ...(ageSeconds ? [`minimumReleaseAge = ${ageSeconds}`] : []),
    ...(ws.minimumReleaseAgeExclude?.length
      ? [`minimumReleaseAgeExcludes = ${JSON.stringify(ws.minimumReleaseAgeExclude)}`]
      : []),
    "",
    "[run]",
    "# `node` in scripts and shebangs resolves to Bun.",
    "bun = true",
    "",
  ].join("\n");
  const bunfigPath = join(ROOT, "bunfig.toml");
  await save(bunfigPath, existsSync(bunfigPath) ? await Bun.file(bunfigPath).text() : "", bunfig);
  if (!check) rmSync(wsFile);
  changed++;
}
if (!String(rootPkg.packageManager ?? "").startsWith("bun@")) rootPkg.packageManager = `bun@${Bun.version}`;
rootPkg.engines = { bun: `>=${rootPkg.packageManager.slice(4)}` };
delete rootPkg.pnpm;
// pnpm-only lifecycle hook: Bun runs `preinstall` before linking.
if (rootPkg.scripts?.["pnpm:devPreinstall"]) {
  rootPkg.scripts.preinstall = rootPkg.scripts["pnpm:devPreinstall"];
  delete rootPkg.scripts["pnpm:devPreinstall"];
}

// ---- 2. Scripts ------------------------------------------------------------------------------
const rewriteCommand = (cmd: string) =>
  cmd
    .replace(/\bcross-env\s+/g, "")
    .replace(/\bpnpm\s+--filter[= ]("[^"]+"|'[^']+'|\S+)\s+(?:run\s+)?/g, "bun --filter $1 run ")
    .replace(/\bpnpm\s+(?:-r|--recursive)\s+(?:run\s+)?/g, "bun --filter '*' run ")
    .replace(/\bpnpm\s+(?:i|install)\b/g, "bun install")
    .replace(/\bpnpm\s+(?:dlx|exec)\s+/g, "bunx ")
    .replace(/\bpnpm\s+run\s+/g, "bun run ")
    .replace(/\bpnpm\s+(?=[\w@.-])/g, "bun run ")
    .replace(/\bnpx\s+/g, "bunx ")
    .replace(/(^|[\s;&|(])node(?=\s)/g, "$1bun");

const scan = async function* (patterns: string[]) {
  const seen = new Set<string>();
  for (const p of patterns)
    for await (const rel of new Glob(p).scan({ cwd: ROOT }))
      if (!rel.includes("node_modules") && !seen.has(rel)) seen.add(rel), yield rel.replaceAll("\\", "/");
};
const PKG_GLOBS = ["package.json", "apps/*/package.json", "packages/*/package.json", "bench/*/package.json", "rspack/package.json", "crates/*/js/package.json", "turbopack/crates/*/js/package.json", "evals/evals/*/package.json"];
for await (const rel of scan(PKG_GLOBS)) {
  const path = join(ROOT, rel);
  const before = rel === "package.json" ? rootText : await Bun.file(path).text();
  const pkg = rel === "package.json" ? rootPkg : JSON.parse(before);
  for (const [k, v] of Object.entries(pkg.scripts ?? {})) pkg.scripts[k] = rewriteCommand(v as string);
  for (const field of ["dependencies", "devDependencies"])
    if (pkg[field]?.["cross-env"]) delete pkg[field]["cross-env"];
  await save(path, before, JSON.stringify(pkg, null, 2) + "\n");
}

// ---- 3. Tooling that spawns pnpm or node ---------------------------------------------------
const TOOL_GLOBS = ["run-tests.js", "scripts/*.js", "scripts/*.mjs", "scripts/*.cjs", "scripts/*.ts", "packages/next/taskfile*.js", "packages/next-swc/*.mjs"];
for await (const rel of scan(TOOL_GLOBS)) {
  if (rel.startsWith("scripts/aphrody/")) continue;
  const path = join(ROOT, rel);
  const before = await Bun.file(path).text();
  const after = before
    .replace(/(['"`])pnpm\1/g, "$1bun$1")
    .replace(/(['"`])pnpm (i|install)\b/g, "$1bun install")
    .replace(/(['"`])pnpm (run )?/g, "$1bun run ")
    .replace(/(['"`])npx /g, "$1bunx ")
    .replace(/(execa|spawn|spawnSync|execFileSync|execFile)\((['"])node\2/g, "$1(process.execPath")
    .replace(/^#!\/usr\/bin\/env node/m, "#!/usr/bin/env bun");
  await save(path, before, after);
}

for (const lock of ["pnpm-lock.yaml"]) {
  const p = join(ROOT, lock);
  if (existsSync(p) && existsSync(join(ROOT, "bun.lock")) && !check) rmSync(p);
}
console.log(check ? `${changed} file(s) not bunified` : `bunified ${changed} file(s)`);
if (check && changed) process.exit(1);
